/*
# Donor passports, donation records and certificate lookups

1. New Tables
- `donor_passports`: one passport per donor, issued with their first recorded donation. Holds a private 64-character passport code that is printed as a QR code.
- `donations`: one row per recorded donation. Stores the date, centre, volume, screening values (weight, haemoglobin, blood pressure, pulse, temperature) and a private 64-character certificate code plus a readable certificate number.

2. Security
- Row level security is enabled on both tables with no policies, so the public API cannot read or write them directly.
- Only the server-side donation recording function (service role) can write these tables.
- Two read-only functions, `get_passport` and `get_certificate`, return the public view of a passport or certificate when the caller knows its code. Codes are random and long, so they cannot be guessed.
- Execute permission on both functions is removed from the public role and granted only to the anonymous and signed-in API roles.

3. Notes
- Next eligible date is calculated as 56 days after the most recent whole-blood donation.
- Codes and certificate numbers are generated by the database when rows are created.
*/

CREATE TABLE IF NOT EXISTS donor_passports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  donor_id uuid NOT NULL UNIQUE REFERENCES donors(id) ON DELETE CASCADE,
  passport_code text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '') CHECK (char_length(passport_code) = 64),
  issued_on timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS donations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  donor_id uuid NOT NULL REFERENCES donors(id) ON DELETE CASCADE,
  passport_id uuid NOT NULL REFERENCES donor_passports(id) ON DELETE CASCADE,
  donated_on date NOT NULL,
  blood_group text NOT NULL CHECK (blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  centre_name text NOT NULL CHECK (char_length(centre_name) BETWEEN 2 AND 120),
  volume_ml integer NOT NULL DEFAULT 450 CHECK (volume_ml BETWEEN 300 AND 500),
  weight_kg numeric(5,1) NOT NULL CHECK (weight_kg BETWEEN 30 AND 250),
  haemoglobin_g_dl numeric(4,1) NOT NULL CHECK (haemoglobin_g_dl BETWEEN 5 AND 25),
  blood_pressure text NOT NULL CHECK (char_length(blood_pressure) BETWEEN 5 AND 12),
  pulse_bpm integer NOT NULL CHECK (pulse_bpm BETWEEN 30 AND 220),
  temperature_c numeric(3,1) NOT NULL CHECK (temperature_c BETWEEN 30 AND 43),
  certificate_code text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '') CHECK (char_length(certificate_code) = 64),
  certificate_number text NOT NULL UNIQUE DEFAULT 'BB-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS donations_donor_date_idx ON donations (donor_id, donated_on DESC);
CREATE INDEX IF NOT EXISTS donations_passport_idx ON donations (passport_id);

ALTER TABLE donor_passports ENABLE ROW LEVEL SECURITY;
ALTER TABLE donations ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE ON donor_passports TO service_role;
GRANT SELECT, INSERT, UPDATE ON donations TO service_role;

CREATE OR REPLACE FUNCTION get_passport(p_code text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  result jsonb;
BEGIN
  IF p_code IS NULL OR char_length(p_code) <> 64 THEN
    RETURN NULL;
  END IF;

  SELECT jsonb_build_object(
    'passport_code', p.passport_code,
    'issued_on', p.issued_on,
    'donor', jsonb_build_object('full_name', d.full_name, 'blood_group', d.blood_group, 'city', d.city),
    'next_eligible_on', (SELECT max(x.donated_on) + 56 FROM donations x WHERE x.passport_id = p.id),
    'donations', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'certificate_code', x.certificate_code,
          'certificate_number', x.certificate_number,
          'donated_on', x.donated_on,
          'centre_name', x.centre_name,
          'volume_ml', x.volume_ml
        ) ORDER BY x.donated_on DESC
      )
      FROM donations x
      WHERE x.passport_id = p.id
    ), '[]'::jsonb)
  )
  INTO result
  FROM donor_passports p
  JOIN donors d ON d.id = p.donor_id
  WHERE p.passport_code = p_code;

  RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION get_certificate(p_code text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  result jsonb;
BEGIN
  IF p_code IS NULL OR char_length(p_code) <> 64 THEN
    RETURN NULL;
  END IF;

  SELECT jsonb_build_object(
    'certificate_number', x.certificate_number,
    'donated_on', x.donated_on,
    'next_eligible_on', x.donated_on + 56,
    'centre_name', x.centre_name,
    'volume_ml', x.volume_ml,
    'blood_group', x.blood_group,
    'passport_code', p.passport_code,
    'donor', jsonb_build_object('full_name', d.full_name, 'city', d.city),
    'screening', jsonb_build_object(
      'weight_kg', x.weight_kg,
      'haemoglobin_g_dl', x.haemoglobin_g_dl,
      'blood_pressure', x.blood_pressure,
      'pulse_bpm', x.pulse_bpm,
      'temperature_c', x.temperature_c
    )
  )
  INTO result
  FROM donations x
  JOIN donor_passports p ON p.id = x.passport_id
  JOIN donors d ON d.id = x.donor_id
  WHERE x.certificate_code = p_code;

  RETURN result;
END;
$$;

REVOKE EXECUTE ON FUNCTION get_passport(text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION get_certificate(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION get_passport(text) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION get_certificate(text) TO anon, authenticated;
